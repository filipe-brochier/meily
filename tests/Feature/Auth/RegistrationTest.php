<?php

use App\Models\User;
use Laravel\Fortify\Features;

beforeEach(function () {
    $this->skipUnlessFortifyHas(Features::registration());
});

test('registration screen can be rendered', function () {
    $response = $this->get(route('register'));

    $response->assertOk();
});

test('new users can register', function () {
    $response = $this->post(route('register.store'), [
        'name' => 'Test User',
        'email' => 'test@example.com',
        'password' => 'password',
        'password_confirmation' => 'password',
    ]);

    $this->assertAuthenticated();
    $response->assertRedirect(route('dashboard', absolute: false));
});

test('new users receive the default categories', function () {
    $this->post(route('register.store'), [
        'name' => 'Test User',
        'email' => 'test@example.com',
        'password' => 'password',
        'password_confirmation' => 'password',
    ]);

    $user = User::where('email', 'test@example.com')->firstOrFail();

    expect($user->categories()->count())->toBe(6)
        ->and($user->categories()->where('type', 'income')->pluck('name')->all())
        ->toEqualCanonicalizing(['Serviço', 'Produto', 'Consultoria'])
        ->and($user->categories()->where('type', 'expense')->pluck('name')->all())
        ->toEqualCanonicalizing(['Transporte', 'Contas', 'Outros']);
});
